import { readFile, writeFile } from 'node:fs/promises';
import { parse } from '@babel/parser';

const source = parse(await readFile(new URL('../src/rocoto-theme.ts', import.meta.url), 'utf8'), { sourceType: 'module', plugins: ['typescript'] });
const declarations = source.program.body.map((statement) => statement.type === 'ExportNamedDeclaration' ? statement.declaration : statement)
  .filter((statement) => statement?.type === 'VariableDeclaration').flatMap((statement) => statement.declarations);
const brand = declarations.find((declaration) => declaration.id.type === 'Identifier' && declaration.id.name === 'BRAND')?.init;
if (brand?.type !== 'ObjectExpression') throw new Error('Read the shared Rocoto brand before building Android.');
const value = (key) => {
  const property = brand.properties.find((entry) => entry.type === 'ObjectProperty' && entry.key.type === 'Identifier' && entry.key.name === key);
  if (property?.value.type !== 'StringLiteral' || !/^#[0-9a-f]{6}$/i.test(property.value.value)) {
    throw new Error(`Rocoto native brand requires the shared ${key} color.`);
  }
  return property.value.value;
};
await writeFile(new URL('app/src/main/res/values/colors.xml', import.meta.url), `<?xml version="1.0" encoding="utf-8"?>
<resources>
    <!-- Generated by android/sync-brand.mjs from app/src/rocoto-theme.ts. -->
    <color name="rocoto_ink">${value('ink')}</color>
    <color name="rocoto_paper">${value('paper')}</color>
</resources>
`);
// The Android launcher uses the canonical mark on paper, independently of the web PWA icon.
const mark = await readFile(new URL('../public/brand/rocoto-mark.svg', import.meta.url), 'utf8');
const paths = [...mark.matchAll(/<path d="([^"]+)"\s*\/>/g)].map((match) => match[1].replace(/\s+/g, ' '));
if (paths.length !== 1 || !mark.includes('translate(0.000000,512.000000) scale(0.100000,-0.100000)')) {
  throw new Error('Update the Android vector conversion for the canonical Rocoto mark.');
}
await writeFile(new URL('app/src/main/res/drawable/rocoto_launcher_mark.xml', import.meta.url), `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated from public/brand/rocoto-mark.svg by android/sync-brand.mjs. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp" android:viewportWidth="512" android:viewportHeight="512">
    <group android:pivotX="256" android:pivotY="256" android:scaleX="0.64" android:scaleY="0.64">
        <group android:translateY="512" android:scaleX="0.1" android:scaleY="-0.1">
            <path android:fillColor="@color/rocoto_ink" android:pathData="${paths[0]}" />
        </group>
    </group>
</vector>
`);
